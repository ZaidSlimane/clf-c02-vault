export function getTotalLectures(): number {
  let total = 0
  for (const d of courseDomains) {
    for (const s of d.sections) {
      total += s.lectures.length
    }
  }
  return total
}

export function getDomainLectures(domainId: string): number {
  const d = courseDomains.find(d => d.id === domainId)
  if (!d) return 0
  return d.sections.reduce((sum, s) => sum + s.lectures.length, 0)
}
